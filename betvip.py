API_URL = "https://wtxmd52.tele68.com/v1/txmd5/sessions"

def get_taixiu_data():
    try:
        r = requests.get(API_URL, timeout=10)
        r.raise_for_status()
        data = r.json()

        if "list" not in data or len(data["list"]) < 15:
            return {"error": "Không đủ dữ liệu cầu"}

        recent = data["list"][:15]

        # ===== BUILD CẦU (CŨ → MỚI) =====
        cau = ""
        for item in reversed(recent):
            raw = item.get("resultTruyenThong", "").upper()
            if raw == "TAI":
                cau += "T"
            elif raw == "XIU":
                cau += "X"

        # ===== MATCH THUẬT TOÁN =====
        du_doan = "Không xác định"
        key_used = ""

        for k in sorted(prediction_table.keys(), key=len, reverse=True):
            if cau.endswith(k):
                du_doan = prediction_table[k]
                key_used = k
                break

        # ===== FALLBACK (KHÔNG CHO API CHẾT) =====
        if du_doan == "Không xác định":
            last12 = cau[-12:]
            t = last12.count("T")
            x = last12.count("X")
            if t > x:
                du_doan = "Tài"
            elif x > t:
                du_doan = "Xỉu"
            else:
                du_doan = "Không vào"
            key_used = last12

        newest = recent[0]
        dice = newest.get("dices", [0, 0, 0])
        tong = newest.get("point", sum(dice))

        return {
            "id": "lc79",
            "phien": newest.get("id"),
            "xucxac1": dice[0],
            "xucxac2": dice[1],
            "xucxac3": dice[2],
            "tong": tong,
            "ketqua": "Tài" if tong >= 11 else "Xỉu",
            "du_doan": du_doan,
            "do_tin_cay": min(len(key_used) * 7, 98),
            "cau": key_used
        }

    except Exception as e:
        return {"error": str(e)}

